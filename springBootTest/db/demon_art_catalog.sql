-- 3. 清理目录外的旧功法（先删习得记录，再删功法本体）
-- ---------------------------------------------------------------------
DELETE ua FROM demon_user_art ua
  JOIN demon_art a ON a.id = ua.art_id
  LEFT JOIN tmp_art_target t ON t.name = a.name
 WHERE t.name IS NULL;

DELETE a FROM demon_art a
  LEFT JOIN tmp_art_target t ON t.name = a.name
 WHERE t.name IS NULL;

SELECT ROW_COUNT() AS 已删除功法;

-- ---------------------------------------------------------------------
-- 4. 主键重排：整体 +1000 挪到安全区，避免逐行改主键撞键
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS tmp_art_id_map;
CREATE TABLE tmp_art_id_map (
  old_id BIGINT NOT NULL PRIMARY KEY,
  new_id BIGINT NOT NULL UNIQUE
);

INSERT INTO tmp_art_id_map (old_id, new_id)
SELECT a.id, t.new_id FROM demon_art a JOIN tmp_art_target t ON t.name = a.name;

SET @diff := (SELECT COUNT(*) FROM demon_art a
                JOIN tmp_art_target t ON t.name = a.name
               WHERE a.id <> t.new_id);
SELECT @diff AS 需重排条数;

UPDATE demon_art SET id = id + 1000 WHERE @diff > 0;

UPDATE demon_user_art ua
  JOIN tmp_art_id_map m ON ua.art_id = m.old_id
   SET ua.art_id = m.new_id
 WHERE @diff > 0;

UPDATE demon_art a
  JOIN tmp_art_id_map m ON a.id = m.old_id + 1000
   SET a.id = m.new_id
 WHERE @diff > 0;

DROP TABLE tmp_art_id_map;

