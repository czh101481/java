-- ---------------------------------------------------------------------
-- 校验一：各境界人数分布（应覆盖引煞 → 无上 十境）
-- ---------------------------------------------------------------------
SELECT r.idx                                   AS 位阶,
       r.name                                  AS 境界,
       COUNT(u.id)                             AS 人数,
       IFNULL(GROUP_CONCAT(u.name ORDER BY u.exp DESC SEPARATOR '、'), '（空缺）') AS 修者
FROM demon_realm r
LEFT JOIN demon_user u ON u.cultivation = r.name
GROUP BY r.idx, r.name
ORDER BY r.idx;

-- ---------------------------------------------------------------------
-- 校验二：新增人物明细
-- ---------------------------------------------------------------------
SELECT id, name AS 道号, realm AS 魔种, cultivation AS 境界, exp AS 煞气, email AS 印记
FROM demon_user
WHERE email LIKE '%@demon.com'
ORDER BY id;
