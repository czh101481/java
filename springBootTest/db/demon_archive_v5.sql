-- 背景：v3 补写了新玩法，v4 把经济数字改成了引用式；但「论道 / 研读 / 道具」
--       三处正文仍停在旧制：论道「一日不过十论」、研读「一日不过五篇，读过则
--       当日不能再读」（且与同篇早已写下的「反复研读所得递减」自相矛盾）、
--       藏宝阁只写限购不写限用。
--       v1.1 把三者改为「每日可重复 + 收益递减 / 每日使用上限」，本脚本同步正文。
--
-- 唯一事实依据：db/BALANCE.md（第七节：每日循环与递减曲线）
--   数字一律不写死，仍沿用 v4 的引用式表述「其数依枢机印刻数」。
--
-- 幂等：多数 UPDATE 带「旧句」守卫（content LIKE '%旧句%'），替换后旧句消失；
--       第 3 条因新句以旧句为前缀，改用「新词不存在」守卫
--       （NOT LIKE '%限购管「买」%'）。两种都保证重跑不会重复追加，
--       执印人日后在后台的手改正文也不会被覆盖。
--       不增删条目，典册仍为 46 条。
--
-- 执行：mysql -uroot -p --default-character-set=utf8mb4 demon_db < 本文件
-- 顺序：demon_archive_v4.sql 之后、demon_daily_v1.sql 前后皆可（脚本只动文字）。
-- =====================================================================
USE demon_db;

-- 1) 研读与习得（path 8）：终身一次 → 每日可重复 + 递减；顺带去掉抄写的「煞气八」
UPDATE demon_archive SET
  content = REPLACE(content,
    '「研读」者，就一篇条目细读到底，当次悟得煞气八。然心神有耗，一日所读不过五篇，读过则当日不能再读。同一篇目反复研读，所得递减——典册的原话是：读一遍是悟，读十遍是执。',
    '「研读」者，就一篇条目细读到底，当次悟得煞气，其数依枢机印刻数。心神有耗，故立今制：一日满额之读有定数，超额再读则所得按次递减，终至无所获——典册的原话是：读一遍是悟，读十遍是执。同一篇目每日只可精读一回，跨子夜又可温故；所谓「读过」只管当日，昨日读过之篇，今日仍可再读。图鉴只录不同篇目，日日温故不增其数。')
WHERE category='path' AND sort_order=8
  AND content LIKE '%一日所读不过五篇，读过则当日不能再读%';

-- 2) 演武场之律（law 7）：论道终身一问 → 每日可再辩 + 递减 + 榜按通论题数
UPDATE demon_archive SET
  content = REPLACE(content,
    '论道之律另计：答中一论得煞气与魔晶之赏，答错则反噬失煞，一日不过十论。论道榜按所答多寡排次，与切磋榜、英杰榜并列。',
    '论道之律另计：答中一论得煞气与魔晶之赏，答错则反噬失煞。同一论题每日只辩一回，跨日又可再辩，非终身一问；当日满额之论有定数，超额再辩所得按次递减，终至无赏。论道榜按所通之不同论题多寡排次，同一论题日日再辩不复累加，与切磋榜、英杰榜并列。')
WHERE category='law' AND sort_order=7
  AND content LIKE '%一日不过十论%';

-- 3) 藏宝阁与乾坤袋（path 16）：补「每日使用上限」两本账 + 破关钥匙同律
UPDATE demon_archive SET
  content = REPLACE(REPLACE(content,
    '每日限购各有定数，逾数则柜上不收；',
    '每日限购各有定数，逾数则柜上不收；每物每日可开之数亦有定数，逾数则囊不肯开——限购管「买」，限用管「用」，两本账分开记，跨子夜各自归零；'),
    '故柜上常有人买了就忘，隔月翻袋才想起自己早备着一枚悟道机缘。',
    '故柜上常有人买了就忘，隔月翻袋才想起自己早备着一枚悟道机缘。今制既立限用，囤积百枚一日倾囊的旧法便行不通了：纵然袋中堆积如山，一日也只用得掉枢机印所许的那几枚。破关之钥亦在此律之内，与寻常丹符同账。')
-- 守卫必须用「新词不存在」：本段的新句以旧句为前缀，若用 LIKE '%旧句%' 判断，
-- 替换后旧句仍在，重跑会把追加段再写一遍（本脚本第一版踩过这个坑）。
WHERE category='path' AND sort_order=16
  AND content NOT LIKE '%限购管「买」%';

-- 4) 藏经殿执印（law 12）：执印人可定限购，也可定限用
UPDATE demon_archive SET
  content = REPLACE(content,
    '物品可改价、设一时之折、定每日限购，公告可立可撤',
    '物品可改价、设一时之折、定每日限购与每日限用，公告可立可撤')
WHERE category='law' AND sort_order=12
  AND content LIKE '%定每日限购，公告可立可撤%';

